/**
 * Get icon HTML by name
 * @param {string} name - icon name
 * @param {number} [size=24] - pixel size
 * @param {string} [color] - optional color override
 * @returns {string} SVG HTML string
 */
function aioIcon(name, size = 24, color = '') {
  const svg = AIOIcons[name] || AIOIcons.diamond;
  const colored = color ? svg.replace('currentColor', color) : svg;
  return size !== 24
    ? colored.replace('width="24"', `width="${size}"`).replace('height="24"', `height="${size}"`)
    : colored;
}

